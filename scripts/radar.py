#!/usr/bin/env python3
"""dotnet-agent-radar maintenance script (standard library only, no telemetry).

Commands
  render [--check]         Regenerate ENTRIES.md and the README top-5 block from data/entries.json.
                           With --check, exit 1 if the committed files are out of date.
  check  [--report FILE]   Compare each entry with live GitHub metadata (last push, archived,
                           license), link-check URLs, write a Markdown report. Never edits verdicts.
  top5   [--write FILE]    Print the top-5 block, or replace the marker block in FILE
                           (for a profile README; not wired into any workflow).

The only network traffic is read-only GET requests to github.com / api.github.com and to
the links listed in the data files. No data is sent anywhere else.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "entries.json"
VERDICTS = ("use", "watch", "avoid")
REQUIRED = ("id", "repo", "name", "category", "verdict", "what", "reason", "pick_if",
            "license", "last_push", "archived")
STALE_DAYS = 180
TOP5_START = "<!-- radar:top5:start -->"
TOP5_END = "<!-- radar:top5:end -->"
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
LINK_RE = re.compile(r"https?://[^\s)>\]\"'`]+")
UA = "dotnet-agent-radar-check"


# ---------------------------------------------------------------- data

def load(path: Path = DATA) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def validate(data: dict) -> list[str]:
    """Return a list of problems (empty when the data file is sound)."""
    problems: list[str] = []
    cats = data.get("categories", {})
    seen_ids: set[str] = set()
    seen_repos: set[str] = set()
    top5: dict[int, str] = {}
    for e in data.get("entries", []):
        eid = e.get("id", "?")
        for k in REQUIRED:
            if k not in e or e[k] in ("", None):
                if k == "archived" and e.get(k) is False:
                    continue
                problems.append(f"{eid}: missing field '{k}'")
        if e.get("verdict") not in VERDICTS:
            problems.append(f"{eid}: verdict must be one of {VERDICTS}")
        if e.get("category") not in cats:
            problems.append(f"{eid}: unknown category '{e.get('category')}'")
        if not REPO_RE.match(str(e.get("repo", ""))):
            problems.append(f"{eid}: bad repo '{e.get('repo')}'")
        if not re.match(r"^\d{4}-\d{2}-\d{2}$", str(e.get("last_push", ""))):
            problems.append(f"{eid}: last_push must be YYYY-MM-DD")
        if eid in seen_ids:
            problems.append(f"{eid}: duplicate id")
        seen_ids.add(eid)
        if e.get("repo") in seen_repos:
            problems.append(f"{eid}: duplicate repo")
        seen_repos.add(e.get("repo"))
        if "top5" in e:
            n = e["top5"]
            if n not in range(1, 6):
                problems.append(f"{eid}: top5 must be 1..5")
            elif n in top5:
                problems.append(f"{eid}: top5 rank {n} already used by {top5[n]}")
            else:
                top5[n] = eid
    return problems


def entry_url(e: dict) -> str:
    return f"https://github.com/{e['repo']}"


# ---------------------------------------------------------------- rendering

def _row_badges(e: dict) -> str:
    arch = "archived" if e.get("archived") else "not archived"
    lic = e["license"]
    if lic in ("none", "NOASSERTION"):
        lic = "no license detected" if lic == "none" else "license not detected by GitHub"
    return f"last push {e['last_push']} | {arch} | {lic}"


def render_entries(data: dict) -> str:
    out = [
        "<!-- GENERATED by scripts/radar.py render from data/entries.json. Do not edit by hand. -->",
        "# Entries",
        "",
        f"Hand-reviewed on {data['reviewed']}. Verdicts: **use** / **watch** / **avoid** "
        "(see the README for what they mean). Freshness values are as recorded at review time; "
        "the weekly workflow compares them with live GitHub data and opens an issue on drift.",
        "",
        "I read each README and the repository metadata. I did not run these tools.",
        "",
    ]
    for cat, title in data["categories"].items():
        members = [e for e in data["entries"] if e["category"] == cat]
        if not members:
            continue
        out += [f"## {title}", ""]
        for e in members:
            out += [
                f"### [{e['name']}]({entry_url(e)}) - {e['verdict'].upper()}",
                "",
                f"`{_row_badges(e)}`",
                "",
                f"- **What it is:** {e['what']}",
                f"- **Why this verdict:** {e['reason']}",
                f"- **Pick this if:** {e['pick_if']}",
            ]
            if e.get("license_note"):
                out.append(f"- **License note:** {e['license_note']}")
            out.append("")
    out += render_comparison(data)
    return "\n".join(out).rstrip() + "\n"


def _md_cell(s: str) -> str:
    return str(s).replace("|", "\\|")


def render_comparison(data: dict) -> list[str]:
    out: list[str] = []
    specs = [
        ("mcp-roslyn", "Comparison: Roslyn MCP servers",
         ("language", "tools", "install")),
        ("mcp-sql", "Comparison: SQL Server MCP servers",
         ("language", "tools", "install", "writes")),
    ]
    labels = {"language": "Language", "tools": "Tools", "install": "Install", "writes": "Writes"}
    for cat, title, cols in specs:
        members = [e for e in data["entries"] if e["category"] == cat]
        if not members:
            continue
        out += [f"## {title}", "",
                "Stars are deliberately left out: they move weekly and do not rank quality. "
                "Tool counts are README claims.", ""]
        head = ["Server", "Verdict", "License", "Last push"] + [labels[c] for c in cols]
        out.append("| " + " | ".join(head) + " |")
        out.append("|" + "|".join(["---"] * len(head)) + "|")
        for e in members:
            f = e.get("facts", {})
            row = [f"[{_md_cell(e['name'])}]({entry_url(e)})", e["verdict"], e["license"],
                   e["last_push"]] + [_md_cell(f.get(c, "n/a")) for c in cols]
            out.append("| " + " | ".join(row) + " |")
        out.append("")
    return out


def top5_entries(data: dict) -> list[dict]:
    ranked = [e for e in data["entries"] if "top5" in e]
    return sorted(ranked, key=lambda e: e["top5"])


def render_top5(data: dict) -> str:
    lines = []
    for e in top5_entries(data):
        lines.append(f"- [{e['name']}]({entry_url(e)}) ({e['verdict']}): pick it if {e['pick_if'].rstrip('.')}.")
    return "\n".join(lines)


def replace_block(text: str, start: str, end: str, content: str) -> str:
    i = text.find(start)
    j = text.find(end)
    if i == -1 or j == -1 or j < i:
        raise ValueError(f"marker block {start} ... {end} not found")
    return text[: i + len(start)] + "\n" + content + "\n" + text[j:]


# ---------------------------------------------------------------- live checks

def default_fetch_json(url: str, token: str | None = None) -> tuple[int, dict | None]:
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/vnd.github+json"})
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=20) as r:  # noqa: S310 - fixed https hosts
            return r.status, json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as ex:
        return ex.code, None
    except (urllib.error.URLError, TimeoutError, OSError):
        return 0, None


def default_head(url: str) -> int:
    for method in ("HEAD", "GET"):
        req = urllib.request.Request(url, method=method, headers={"User-Agent": UA})
        try:
            with urllib.request.urlopen(req, timeout=20) as r:  # noqa: S310
                return r.status
        except urllib.error.HTTPError as ex:
            if method == "HEAD" and ex.code in (403, 405):
                continue
            return ex.code
        except (urllib.error.URLError, TimeoutError, OSError):
            return 0
    return 0


def live_row(repo: str, fetch=default_fetch_json, token: str | None = None) -> dict:
    status, body = fetch(f"https://api.github.com/repos/{repo}", token)
    if status == 200 and body:
        lic = (body.get("license") or {}).get("spdx_id") or "none"
        return {"status": 200, "last_push": (body.get("pushed_at") or "")[:10],
                "archived": bool(body.get("archived")), "license": lic}
    return {"status": status}


def compare(entry: dict, live: dict, today: dt.date, stale_days: int = STALE_DAYS) -> list[str]:
    """Findings that need a human decision. Verdicts are never changed automatically."""
    st = live.get("status")
    if st in (404, 410, 301):
        return [f"repository not found or moved (HTTP {st})"]
    if st != 200:
        return [f"could not read repository metadata (HTTP {st}); check later"]
    out = []
    if live["archived"] and not entry.get("archived"):
        out.append("now ARCHIVED upstream; verdict probably needs to become avoid")
    if not live["archived"] and entry.get("archived"):
        out.append("no longer archived upstream; re-review")
    if live["license"] != entry["license"]:
        out.append(f"license changed: recorded {entry['license']}, live {live['license']}")
    try:
        age = (today - dt.date.fromisoformat(live["last_push"])).days
    except ValueError:
        age = None
    if age is not None and age > stale_days and entry["verdict"] != "avoid":
        out.append(f"no push for {age} days (limit {stale_days}); consider downgrading the verdict")
    return out


def extract_links(text: str) -> list[str]:
    links = [m.group(0).rstrip(".,;:") for m in LINK_RE.finditer(text)]
    return sorted(set(links))


SOFT = {0, 403, 429, 999}


def check_links(urls: list[str], head=default_head) -> list[tuple[str, int]]:
    """Return (url, status) for links that look broken. 0/403/429 are reported as 'unverified'."""
    bad = []
    for u in urls:
        s = head(u)
        if s >= 400 or s == 0:
            bad.append((u, s))
    return bad


def build_report(data: dict, lives: dict, link_problems: list[tuple[str, int]],
                 today: dt.date, stale_days: int = STALE_DAYS) -> tuple[str, int]:
    findings = 0
    rows = ["| Entry | Verdict | Recorded push | Live push | Archived | License | Findings |",
            "|---|---|---|---|---|---|---|"]
    notes = []
    for e in data["entries"]:
        if e["id"] not in lives:  # offline run: nothing to compare
            rows.append(f"| [{e['name']}]({entry_url(e)}) | {e['verdict']} | {e['last_push']} | - | - | - | not checked |")
            continue
        lv = lives[e["id"]]
        fs = compare(e, lv, today, stale_days)
        findings += len(fs)
        if lv.get("status") == 200:
            cells = [lv["last_push"], "yes" if lv["archived"] else "no", lv["license"]]
        else:
            cells = ["?", "?", "?"]
        rows.append(f"| [{e['name']}]({entry_url(e)}) | {e['verdict']} | {e['last_push']} | "
                    + " | ".join(cells) + f" | {len(fs) or 'ok'} |")
        for f in fs:
            notes.append(f"- **{e['name']}** ({e['verdict']}): {f}")
    hard = [(u, s) for u, s in link_problems if s not in SOFT]
    soft = [(u, s) for u, s in link_problems if s in SOFT]
    findings += len(hard)
    out = [f"Automated freshness report for {today.isoformat()}. "
           "This job never edits verdicts; a human decides what to change.", ""]
    out += ["## Findings", ""]
    out += notes or ["- No drift found in last push, archive state or license."]
    out += ["", "## Broken links", ""]
    out += [f"- {u} (HTTP {s})" for u, s in hard] or ["- None."]
    if soft:
        out += ["", "## Links not verified (rate-limited or unreachable)", ""]
        out += [f"- {u} (HTTP {s})" for u, s in soft]
    out += ["", "## Freshness table", ""] + rows
    return "\n".join(out) + "\n", findings


# ---------------------------------------------------------------- CLI

def cmd_render(check: bool) -> int:
    data = load()
    problems = validate(data)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 2
    entries_md = render_entries(data)
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    new_readme = replace_block(readme, TOP5_START, TOP5_END, render_top5(data))
    targets = {ROOT / "ENTRIES.md": entries_md, readme_path: new_readme}
    stale = []
    for path, text in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            stale.append(path.name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("out of date: " + ", ".join(stale) + " (run: python scripts/radar.py render)", file=sys.stderr)
        return 1
    return 0


def cmd_check(report: str | None, offline: bool) -> int:
    data = load()
    problems = validate(data)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 2
    token = os.environ.get("GITHUB_TOKEN")
    today = dt.date.today()
    lives = {}
    urls = set()
    for e in data["entries"]:
        urls.add(entry_url(e))
    for p in [ROOT / "README.md", ROOT / "CONTRIBUTING.md", ROOT / "ENTRIES.md"]:
        if p.exists():
            urls.update(extract_links(p.read_text(encoding="utf-8")))
    link_problems: list[tuple[str, int]] = []
    if not offline:
        for e in data["entries"]:
            lives[e["id"]] = live_row(e["repo"], token=token)
        link_problems = check_links(sorted(urls))
    text, findings = build_report(data, lives, link_problems, today)
    if report:
        Path(report).write_text(text, encoding="utf-8", newline="\n")
    else:
        print(text)
    print(f"findings: {findings}", file=sys.stderr)
    return 0


def cmd_top5(write: str | None) -> int:
    data = load()
    block = render_top5(data)
    if not write:
        print(block)
        return 0
    p = Path(write)
    p.write_text(replace_block(p.read_text(encoding="utf-8"), TOP5_START, TOP5_END, block),
                 encoding="utf-8", newline="\n")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render")
    r.add_argument("--check", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("--report")
    c.add_argument("--offline", action="store_true", help="skip network; report only data problems")
    t = sub.add_parser("top5")
    t.add_argument("--write")
    a = ap.parse_args(argv)
    if a.cmd == "render":
        return cmd_render(a.check)
    if a.cmd == "check":
        return cmd_check(a.report, a.offline)
    return cmd_top5(a.write)


if __name__ == "__main__":
    sys.exit(main())
